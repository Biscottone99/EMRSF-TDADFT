    handle.write("G SPIN FACTOR             sqrt(2), fixed by Table S3\n")
    handle.write("CO1/O2V COMBINATION       S1-S2, fixed by spin adaptation\n")
    handle.write(
        f"MRSF S0 ENERGY            {audit.mrsf_ground_energy_hartree: .12f} Eh\n"
    )
    handle.write(
        f"EMRSF S0 ENERGY           {audit.emrsf_ground_energy_hartree: .12f} Eh\n"
    )
    handle.write(
        f"EXACT S0 SHIFT            {audit.exact_ground_shift_hartree: .12f} Eh"
        f"  {audit.exact_ground_shift_ev: .8f} eV\n"
    )
    handle.write(f"EMRSF S0 gamma_CV         {audit.gamma_cv_ground: .12f}\n")
    handle.write(f"||C.T S0||                {audit.coupling_norm: .12e}\n")
    handle.write(f"||Fock part||             {audit.fock_norm: .12e}\n")
    handle.write(f"||two-electron part||     {audit.two_electron_norm: .12e}\n")
