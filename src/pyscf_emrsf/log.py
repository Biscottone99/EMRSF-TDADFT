def _line(handle, character: str = "-", width: int = 79) -> None:
    handle.write(character * width + "\n")


def _basis_label(mol) -> str:
    basis = getattr(mol, "basis", "unknown")
    if isinstance(basis, str):
        return basis
    if isinstance(basis, dict):
        values = sorted({str(value) for value in basis.values()})
        return ", ".join(values)
    return str(basis)


def _value_label(value) -> str:
    """Return a compact label for scalar, dictionary, or per-atom settings."""

    if value is None:
        return "none"
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        items = sorted({str(item) for item in value.values()})
        return ", ".join(items)
    return str(value)


def _method_label(ref) -> str:
    mf = ref.mf
    if hasattr(mf, "xc"):
        return f"ROKS/{mf.xc}"
    return "ROHF"


def _write_header(
    handle,
    ref,
    *,
    calculation: str,
    target_multiplicity: int,
    title: str | None,
) -> None:
    mol = ref.mf.mol
    _line(handle, "=")
    handle.write("                  P y S C F - E M R S F\n")
    handle.write("    EMRSF-SOC/eigenvector export release v0.8.0\n")
    _line(handle, "=")
    handle.write("This is an ORCA-style human-readable report generated by\n")
    handle.write("PySCF-EMRSF.  It is not an ORCA output file.\n\n")
    handle.write(f"JOB TITLE            {title or 'untitled'}\n")
    handle.write(f"CALCULATION          {calculation}\n")
    handle.write(f"METHOD               {_method_label(ref)}\n")
    handle.write(f"BASIS                {_basis_label(mol)}\n")
    with_df = getattr(ref.mf, "with_df", None)
    handle.write(f"DENSITY FITTING      {with_df is not None}\n")
    if with_df is not None:
        handle.write(
            f"AUXILIARY BASIS      {_value_label(getattr(with_df, 'auxbasis', None))}\n"
        )
    if hasattr(ref.mf, "xc"):
        grid = getattr(ref.mf, "grids", None)
        handle.write(
            f"SCF XC GRID LEVEL    {getattr(grid, 'level', 'unknown')}\n"
        )
        coordinates = getattr(grid, "coords", None)
        points = len(coordinates) if coordinates is not None else 0
        handle.write(f"SCF XC GRID POINTS   {points:d}\n")
        handle.write(
            f"SCF XC GRID PRUNED   {getattr(grid, 'prune', None) is not None}\n"
        )
    pcm = pcm_metadata(ref.mf)
    if pcm is None:
        handle.write("PCM SOLVATION        False\n")
    else:
        handle.write("PCM SOLVATION        True\n")
        handle.write(f"PCM METHOD           {pcm['method']}\n")
        handle.write(f"PCM EPSILON          {float(pcm['epsilon']):.8f}\n")
        handle.write(f"PCM LEBEDEV ORDER    {int(pcm['lebedev_order'])}\n")
        handle.write("PCM RESPONSE SCOPE   reference-state; frozen in MRSF/EMRSF response\n")
    handle.write(
        f"SCF CONV. TOL.      {float(getattr(ref.mf, 'conv_tol', np.nan)): .3e}\n"
    )
    handle.write(
        "SCF GRAD. TOL.      "
        f"{float(getattr(ref.mf, 'conv_tol_grad', None) or np.nan): .3e}\n"
    )
    handle.write(
        "DIRECT SCF TOL.     "
        f"{float(getattr(ref.mf, 'direct_scf_tol', np.nan)): .3e}\n"
    )
    if hasattr(ref.mf, "small_rho_cutoff"):
        handle.write(
            "SMALL RHO CUTOFF    "
            f"{float(ref.mf.small_rho_cutoff): .3e}\n"
        )
    handle.write(f"SCF MAX CYCLES      {int(getattr(ref.mf, 'max_cycle', 0)):d}\n")
    handle.write(f"MOLECULAR CHARGE     {mol.charge:d}\n")
    handle.write(f"REFERENCE MULT.      {mol.spin + 1:d}\n")
    handle.write(f"TARGET MULT.         {int(target_multiplicity):d}\n")
    handle.write(f"POINT GROUP          {getattr(mol, 'groupname', 'C1') or 'C1'}\n")
    handle.write(f"ELECTRONS            {mol.nelectron:d}\n")
    handle.write(f"AO FUNCTIONS         {ref.nao:d}\n")
    handle.write(f"MO FUNCTIONS         {ref.nmo:d}\n")
    run_metadata = dict(getattr(ref.mf, "emrsf_run_metadata", {}))
    if run_metadata:
        handle.write(
            f"RESPONSE METHOD       {run_metadata.get('method', 'unknown')}\n"
        )
        handle.write(
            "RESPONSE INTEGRALS    "
            f"{run_metadata.get('integral_backend', 'unknown')}\n"
        )
        handle.write(
            "RESPONSE EIG. TOL.    "
            f"{float(run_metadata.get('eigenvalue_tolerance', np.nan)): .3e}\n"
        )
        handle.write(
            "RESPONSE RES. TOL.    "
            f"{float(run_metadata.get('residual_tolerance', np.nan)): .3e}\n"
        )
    handle.write(f"TIMESTAMP UTC        {datetime.now(timezone.utc).isoformat()}\n")


def _write_geometry(handle, ref) -> None:
    mol = ref.mf.mol
    coordinates = np.asarray(mol.atom_coords()) * BOHR_TO_ANGSTROM
    handle.write("\nCARTESIAN COORDINATES (ANGSTROEM)\n")
    _line(handle)
    handle.write("  No. Element              X              Y              Z\n")
    for atom, coordinate in enumerate(coordinates):
        handle.write(
            f"{atom + 1:5d} {mol.atom_symbol(atom):>3s}"
            f" {coordinate[0]:14.8f} {coordinate[1]:14.8f} {coordinate[2]:14.8f}\n"
        )


def _write_reference(handle, ref) -> None:
    mf = ref.mf
    diagnostics = ref.diagnostics
    metadata = dict(getattr(mf, "emrsf_reference_metadata", {}))
    handle.write("\nTRIPLET REFERENCE\n")
    _line(handle)
    handle.write(f"REFERENCE SOURCE      {diagnostics.source}\n")
    if diagnostics.source_path:
        handle.write(f"REFERENCE SOURCE FILE {diagnostics.source_path}\n")
    handle.write(f"LOCAL SCF RUN         {diagnostics.local_scf_run}\n")
    handle.write(f"LOCAL SCF CONVERGED   {diagnostics.local_scf_converged}\n")
    handle.write(f"REFERENCE READY       {bool(getattr(mf, 'converged', False))}\n")
    if metadata.get("scf_strategy") is not None:
        handle.write(f"SCF STRATEGY          {metadata['scf_strategy']}\n")
        handle.write(
            f"SCF FINAL STAGE       {metadata.get('scf_final_stage', 'unknown')}\n"
        )
        handle.write(
            f"SCF RESCUE USED       {bool(metadata.get('scf_rescue_used', False))}\n"
        )
        handle.write(
            "SCF 2-CYCLE DETECTED "
            f"{bool(metadata.get('scf_oscillation_detected', False))}\n"
        )
        handle.write(
            "SCF DENSITY AVG GUESS "
            f"{bool(metadata.get('scf_density_averaging_used', False))}\n"
        )
        attempts = tuple(metadata.get("scf_attempt_history", ()))
        handle.write(f"SCF ATTEMPT COUNT     {len(attempts):d}\n")
        for index, attempt in enumerate(attempts, start=1):
            handle.write(
                f"SCF ATTEMPT {index:02d}        "
                f"{attempt.get('name', 'unknown')} | "
                f"{attempt.get('converger', 'unknown')} | "
                f"converged={bool(attempt.get('converged', False))} | "
                f"cycles={int(attempt.get('cycles', 0))} | "
                f"E={float(attempt.get('energy_hartree', np.nan)):.12f} Eh | "
                f"g={float(attempt.get('gradient_norm', np.nan)):.3e} | "
                f"dP={float(attempt.get('density_change_norm', np.nan)):.3e} | "
                "two_cycle="
                f"{bool(attempt.get('oscillation_detected', False))}\n"
            )
    handle.write(f"SCF ENERGY / Eh       {float(getattr(mf, 'e_tot', np.nan)): .14f}\n")
    handle.write(f"CLOSED ORBITALS       {len(ref.closed):d}\n")
    handle.write(f"OPEN ORBITALS O1/O2   {ref.o1 + 1:d}  {ref.o2 + 1:d}\n")
    handle.write(f"VIRTUAL ORBITALS      {len(ref.virtual):d}\n")
    if metadata.get("input_orthonormality_error") is not None:
        handle.write(
            "MOLDEN INPUT S-ORTH ERR "
            f"{float(metadata['input_orthonormality_error']): .6e}\n"
        )
    if metadata.get("basis_projection") is not None:
        handle.write(
            f"MOLDEN BASIS PROJECTED {bool(metadata['basis_projection'])}\n"
        )
    handle.write(
        f"FINAL S-ORTH ERROR    {diagnostics.orthonormality_error: .6e}\n"
    )
    handle.write(
        f"ELECTRON TRACE ERROR  {diagnostics.electron_number_error: .6e}\n"
    )
    handle.write(f"SPIN TRACE ERROR      {diagnostics.spin_number_error: .6e}\n")
    handle.write(
        f"ORBITAL GRADIENT MAX  {diagnostics.orbital_gradient_max: .6e}\n"
    )
    handle.write(
        f"ORBITAL GRADIENT RMS  {diagnostics.orbital_gradient_rms: .6e}\n"
    )
    handle.write(
        "MIN ORBITAL SYM WEIGHT "
        f"{diagnostics.minimum_orbital_symmetry_weight: .10f}\n"
    )
    handle.write(
        "GAP CLOSED->O1 / Eh "
        f"{diagnostics.closed_to_o1_gap_hartree: .10f}\n"
    )
    handle.write(
        f"GAP O1->O2 / Eh       {diagnostics.o1_to_o2_gap_hartree: .10f}\n"
    )
    handle.write(
        "GAP O2->VIRTUAL / Eh "
        f"{diagnostics.o2_to_virtual_gap_hartree: .10f}\n"
    )
    if diagnostics.seed_somo_singular_values:
        values = " ".join(
            f"{value:.10f}" for value in diagnostics.seed_somo_singular_values
        )
        handle.write(f"SEED SOMO SINGULAR VAL {values}\n")
    if diagnostics.seed_alpha_occupied_min_singular_value is not None:
        handle.write(
            "SEED ALPHA OCC MIN SV "
            f"{diagnostics.seed_alpha_occupied_min_singular_value:.10f}\n"
        )
    if diagnostics.seed_beta_occupied_min_singular_value is not None:
        handle.write(
            "SEED BETA OCC MIN SV  "
            f"{diagnostics.seed_beta_occupied_min_singular_value:.10f}\n"
        )
    handle.write(
        "REFERENCE WARNINGS    "
        + (", ".join(diagnostics.warnings) if diagnostics.warnings else "NONE")
        + "\n"
    )
    handle.write("\nORBITAL ENERGIES\n")
    handle.write("  MO   SYM       OCC          EPSILON / Eh          EPSILON / eV\n")
    irreps = orbital_irrep_names(ref)
    for orbital, (occupation, energy, irrep) in enumerate(
        zip(ref.occupation, ref.energy, irreps), start=1
    ):
        handle.write(
            f"{orbital:5d} {irrep:>5s} {occupation:9.4f} {energy:21.12f}"
            f" {energy * HARTREE_TO_EV:21.8f}\n"
        )


def _mrsf_configuration_name(space, pair: tuple[int, int]) -> str:
    i, a = pair
    ref = space.ref
    if pair == (ref.o2, ref.o1):
        return "G"
    if pair == (ref.o1, ref.o2):
        return "D"
    if pair == (ref.o1, ref.o1):
        return "OOS"
    if i in set(ref.closed) and a == ref.o1:
        return "CO1"
    if i in set(ref.closed) and a == ref.o2:
        return "CO2"
    if i == ref.o1 and a in set(ref.virtual):
        return "O1V"
    if i == ref.o2 and a in set(ref.virtual):
        return "O2V"
    if i in set(ref.closed) and a in set(ref.virtual):
        return "CV(MRSF)"
    return "MRSF"


def _write_mrsf_configurations(
    handle, result, state: int, *, top_configurations: int
) -> None:
    vector = result.eigenvectors[:, state]
    order = np.argsort(np.abs(vector))[::-1]
    printed = 0
    for index in order:
        amplitude = float(vector[index])
        if abs(amplitude) < 1.0e-10:
            continue
        i, a = result.space.labels[index]
        name = _mrsf_configuration_name(result.space, (i, a))
        handle.write(
            f"    {name:<10s} {i + 1:5d} -> {a + 1:<5d}"
            f"  c={amplitude: .9f}  w={amplitude * amplitude: .9f}\n"
        )
        printed += 1
        if printed >= top_configurations:
            break


def _write_mrsf_states(handle, result, *, top_configurations: int) -> None:
    manifold = "SINGLET" if result.target_multiplicity == 1 else "TRIPLET"
    state0 = "singlet" if result.target_multiplicity == 1 else "triplet"
    handle.write(f"\nMRSF-TDDFT/TDA {manifold} STATES\n")
    _line(handle)
    handle.write("Root energies are relative to the high-spin response reference;\n")
    handle.write(
        f"excitation energies are relative to the lowest MRSF {state0} root.\n\n"
    )
    symmetries = result.state_symmetries()
    terms = term_labels(symmetries)
    for state, energy in enumerate(result.eigenvalues):
        state_symmetry = symmetries[state]
        handle.write(
            f"STATE {state:3d}: E={energy: .12f} Eh"
            f"  EXC={result.excitation_energies_ev[state]: .8f} eV"
            f"  SYM={state_symmetry.label}"
            f"  TERM={terms[state]}"
            f"  PURITY={state_symmetry.purity: .8f}\n"
        )
        _write_mrsf_configurations(
            handle, result, state, top_configurations=top_configurations
        )


def _write_solver_diagnostics(handle, result, label: str) -> None:
    handle.write(f"\n{label} EIGENSOLVER\n")
    _line(handle)
    handle.write(f"SOLVER               {result.solver}\n")
    handle.write(
        f"MATRIX STORAGE       {'DENSE' if result.matrix is not None else 'MATRIX-FREE'}\n"
    )
    if result.iterations is not None:
        handle.write(f"ITERATIONS           {result.iterations:d}\n")
    if result.matvecs is not None:
        handle.write(f"MATVECS              {result.matvecs:d}\n")
    if result.initial_guesses is not None:
        handle.write(f"INITIAL GUESSES      {result.initial_guesses:d}\n")
    if result.symmetry_seed_counts:
        if hasattr(result, "space"):
            groupname = result.space.ref.mf.mol.groupname
        elif hasattr(result, "mrsf_space"):
            groupname = result.mrsf_space.ref.mf.mol.groupname
        else:
            groupname = result.mrsf_result.space.ref.mf.mol.groupname
        from pyscf import symm

        values = []
        for irrep_id, count in result.symmetry_seed_counts:
            try:
                label_name = symm.irrep_id2name(groupname, int(irrep_id))
            except (KeyError, ValueError):
                label_name = str(irrep_id)
            values.append(f"{label_name}:{count}")
        handle.write(f"SEEDS PER IRREP      {' '.join(values)}\n")
    if result.converged is not None:
        handle.write(
            "ROOTS CONVERGED      "
            f"{int(np.count_nonzero(result.converged)):d}/{len(result.converged):d}\n"
        )
    if result.residual_norms is not None:
        handle.write(
            f"MAX RESIDUAL NORM    {float(np.max(result.residual_norms)): .6e}\n"
        )


def _descriptor_map(descriptors) -> dict[int, object]:
    if descriptors is None:
        return {}
    return {int(value.state_index): value for value in descriptors}


def _write_descriptors(handle, descriptors) -> None:
    values = _descriptor_map(descriptors)
    if not values:
        return
    handle.write("\nDENSITY-DIFFERENCE CHARGE-TRANSFER ANALYSIS (SI S42-S47)\n")
    _line(handle)
    handle.write("rho_ref is the triplet-reference density.  q is the symmetric\n")
    handle.write("average of the finite-grid positive and negative integrals.\n")
    handle.write("Both S45 centroids use this common q denominator, as printed in SI.\n")
    handle.write("mu=q*D_CT is reported in e*Angstrom (paper convention), e*bohr,\n")
    handle.write("and Debye.  Integral residuals expose quadrature convergence.\n")
    for state in sorted(values):
        value = values[state]
        handle.write(f"\nMRSF STATE {state:d}\n")
        handle.write(f"  S42  integral Delta rho       {value.integral_delta_rho: .10e} e\n")
        handle.write(f"  S43  positive/negative fields evaluated on molecular grid\n")
        handle.write(f"  S44  q+                       {value.q_plus: .10f} e\n")
        handle.write(f"       q-                       {value.q_minus: .10f} e\n")
        handle.write(f"       q=(q+ + q-)/2            {value.q: .10f} e\n")
        handle.write(f"       q+ - q-                  {value.charge_imbalance: .10e} e\n")
        handle.write(
            "  S45  R+ / Angstrom            "
            f"{value.r_plus_angstrom[0]: .8f} {value.r_plus_angstrom[1]: .8f}"
            f" {value.r_plus_angstrom[2]: .8f}\n"
        )
        handle.write(
            "       R- / Angstrom            "
            f"{value.r_minus_angstrom[0]: .8f} {value.r_minus_angstrom[1]: .8f}"
            f" {value.r_minus_angstrom[2]: .8f}\n"
        )
        handle.write(f"  S46  D_CT                     {value.d_ct_angstrom: .10f} Angstrom\n")
        handle.write(f"                                {value.d_ct_bohr: .10f} bohr\n")
        handle.write(f"  S47  mu=q*D_CT                {value.mu_e_angstrom: .10f} e*Angstrom\n")
        handle.write(f"                                {value.mu_e_bohr: .10f} e*bohr\n")
        handle.write(f"                                {value.mu_debye: .10f} Debye\n")
        handle.write(
            f"  GRID level/points/pruned      {value.grid_level:d} /"
            f" {value.grid_points:d} / {value.grid_pruned}\n"
        )
        handle.write(
            f"  GRID electrons ref/state      {value.reference_electrons_grid: .10f} /"
            f" {value.state_electrons_grid: .10f}\n"
        )


def _write_transition_properties(
    handle, properties, *, target_multiplicity: int = 1
) -> None:
    if not properties:
        return
    handle.write("\nMRSF ELECTRIC-DIPOLE TRANSITION PROPERTIES (LENGTH GAUGE)\n")
    _line(handle)
    handle.write(
        "Properties use the spin-adapted MRSF state-to-state transition 1-RDM.\n"
    )
    manifold = "S0 -> Sn" if int(target_multiplicity) == 1 else "T0 -> Tn"
    handle.write(f"TRANSITION MANIFOLD  {manifold}\n")
    handle.write("Dipoles are in e*bohr.  When printed in an EMRSF report, these\n")
    handle.write("are explicitly the companion MRSF values, not full EMRSF strengths.\n\n")
    handle.write(
        " INITIAL FINAL      DELTA_E/eV          MUX          MUY          MUZ"
        "       |MU|             f       Tr(D_if)\n"
    )
    for value in properties:
        dipole = value.transition_dipole_e_bohr
        handle.write(
            f" {value.initial_state:7d} {value.final_state:5d}"
            f" {value.excitation_energy_ev:15.8f}"
            f" {dipole[0]:12.7f} {dipole[1]:12.7f} {dipole[2]:12.7f}"
            f" {value.transition_dipole_norm_e_bohr:10.7f}"
            f" {value.oscillator_strength:13.8f}"
            f" {value.transition_density_trace:13.5e}\n"
        )


def _write_emrsf_configurations(
    handle, result, state: int, *, top_configurations: int
) -> None:
    vector = result.eigenvectors[:, state]
    mrsf_space = result.mrsf_space
    entries = []
    for reduced, full in enumerate(result.live_mrsf_indices):
        i, a = mrsf_space.labels[int(full)]
        entries.append(
            (
                abs(vector[reduced]),
                vector[reduced],
                _mrsf_configuration_name(mrsf_space, (i, a)),
                i,
                a,
            )
        )
    for offset, (i, a) in enumerate(result.cv_space.labels):
        index = result.mrsf_size + offset
        entries.append((abs(vector[index]), vector[index], "CV(LR)", i, a))
    entries.sort(key=lambda item: item[0], reverse=True)
    for _, amplitude, name, i, a in entries[:top_configurations]:
        handle.write(
            f"    {name:<10s} {i + 1:5d} -> {a + 1:<5d}"
            f"  c={amplitude: .9f}  w={amplitude * amplitude: .9f}\n"
        )


