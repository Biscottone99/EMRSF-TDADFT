def _write_lr_cv_diagonal_audit(handle, audit) -> None:
    if audit is None:
        return
    handle.write("\nADDED LR-CV DIAGONAL AUDIT (SI S30-S39)\n")
    _line(handle, "-")
    handle.write(
        "Each A_CV diagonal is decomposed into the raw closed-shell Fock "
        "difference,\n"
    )
    handle.write(
        "the S30 correction, Coulomb response, global exact exchange, and "
        "the\n"
    )
    handle.write(
        "semilocal XC kernel. Explicit SI-S23 A_G is then added exactly once.\n"
    )
    handle.write(
        "All table entries are in Eh. CHECK rows are independently evaluated "
        "with\n"
    )
    handle.write("the complete matrix-free EMRSF operator.\n\n")
    handle.write(f"S30 APPLIED                 {audit.apply_fock_correction}\n")
    handle.write(f"GLOBAL HF EXCHANGE c_H      {audit.exact_exchange: .12f}\n")
    handle.write(f"AO RESPONSE BATCH SIZE      {audit.batch_size:d}\n")
    handle.write(
        f"A_G EXPLICIT SI S23         {audit.ground_offset_hartree: .12f} Eh"
        f"  {audit.ground_offset_hartree * HARTREE_TO_EV: .8f} eV\n"
    )
    handle.write(
        f"A_G FROM MRSF OPERATOR      "
        f"{audit.ground_offset_recomputed_hartree: .12f} Eh\n"
    )
    handle.write(
        f"A_G SOURCE ERROR            "
        f"{audit.ground_offset_source_error_hartree: .6e} Eh\n"
    )
    handle.write(
        f"MAX DIRECT DIAGONAL ERROR   "
        f"{audit.maximum_direct_check_error_hartree: .6e} Eh"
        f"  {audit.maximum_direct_check_error_ev: .6e} eV\n\n"
    )
    handle.write(
        " IDX      C -> V       raw Fock          S30            J"
        "          exact-X      semilocal-XC          A_G          total\n"
    )
    for index, (i, a) in enumerate(audit.labels):
        handle.write(
            f" {index:4d} {i + 1:6d} -> {a + 1:<6d}"
            f" {audit.raw_fock_hartree[index]:14.8f}"
            f" {audit.s30_hartree[index]:12.8f}"
            f" {audit.coulomb_hartree[index]:12.8f}"
            f" {audit.exact_exchange_hartree[index]:14.8f}"
            f" {audit.xc_kernel_hartree[index]:17.8f}"
            f" {audit.ground_offset_hartree:12.8f}"
            f" {audit.emrsf_diagonal_hartree[index]:14.8f}\n"
        )

    handle.write("\nREPRESENTATIVE COMPLETE-MATVEC CHECKS\n")
    handle.write(
        " IDX      C -> V        component sum       direct matvec"
        "          difference\n"
    )
    for position, index in enumerate(audit.direct_check_indices):
        i, a = audit.labels[int(index)]
        handle.write(
            f" {int(index):4d} {i + 1:6d} -> {a + 1:<6d}"
            f" {audit.emrsf_diagonal_hartree[index]:18.10f}"
            f" {audit.direct_check_hartree[position]:18.10f}"
            f" {audit.direct_check_error_hartree[position]:15.6e}\n"
        )


def write_mrsf_log(
    result,
    path,
    *,
    descriptors=None,
    transition_properties=None,
    title: str | None = None,
    top_configurations: int = 8,
) -> Path:
    """Write a complete MRSF report and return its path."""

    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as handle:
        _write_header(
            handle,
            result.space.ref,
            calculation="MRSF-TDDFT/TDA",
            target_multiplicity=result.target_multiplicity,
            title=title,
        )
        _write_geometry(handle, result.space.ref)
        _write_reference(handle, result.space.ref)
        handle.write(f"\nRAW MRSF SPACE       {result.space.size:d}\n")
        handle.write(f"COMPUTED ROOTS       {len(result.eigenvalues):d}\n")
        _write_solver_diagnostics(handle, result, "MRSF")
        _write_mrsf_states(
            handle, result, top_configurations=int(top_configurations)
        )
        _write_descriptors(handle, descriptors)
        _write_transition_properties(
            handle,
            transition_properties,
            target_multiplicity=result.target_multiplicity,
        )
        _write_footer(handle)
    return output


def write_emrsf_log(
    result,
    path,
    *,
    descriptors=None,
    transition_properties=None,
    coupling_audit=None,
    lr_cv_audit=None,
    title: str | None = None,
    top_configurations: int = 8,
) -> Path:
    """Write MRSF, EMRSF, CV, state-matching, and S42--S47 information."""

    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    ref = result.cv_space.ref
    with output.open("w", encoding="utf-8") as handle:
        _write_header(
            handle,
            ref,
            calculation="EMRSF-TDDFT/TDA",
            target_multiplicity=result.target_multiplicity,
            title=title,
        )
        _write_geometry(handle, ref)
        _write_reference(handle, ref)
        handle.write(f"\nRAW MRSF SPACE       {result.mrsf_space.size:d}\n")
        handle.write(f"LIVE MRSF SPACE      {result.mrsf_size:d}\n")
        handle.write(f"ADDED LR C->V SPACE  {result.cv_space.size:d}\n")
        handle.write(f"EMRSF OPERATOR DIM.  {result.eigenvectors.shape[0]:d}\n")
        handle.write(f"COMPUTED ROOTS       {len(result.eigenvalues):d}\n")
        handle.write(f"DIRECT EMRSF MODE    {result.direct_emrsf}\n")
        handle.write(
            "MRSF PRE-DIAGONAL.   "
            f"{result.mrsf_result is not None}\n"
        )
        handle.write(f"INTEGRAL BACKEND     {result.integral_backend}\n")
        if result.exact_exchange is not None:
            handle.write(f"HF EXCHANGE c_H      {result.exact_exchange: .12f}\n")
        if result.coupling_scale is not None:
            handle.write(f"COUPLING SCALE c_cp  {result.coupling_scale: .12f}\n")
        if result.target_multiplicity == 1:
            handle.write("G SPIN FACTOR        sqrt(2), fixed by Table S3\n")
            handle.write("OOS SPIN COMBINATION (L-R)/sqrt(2)\n")
            handle.write("CO1 TABLE COMBINATION S1-S2, fixed\n")
            handle.write("O2V TABLE COMBINATION S1-S2, fixed\n")
        else:
            handle.write("G/D CONFIGURATIONS   absent from triplet space\n")
            handle.write("OOS SPIN COMBINATION (L+R)/sqrt(2)\n")
            handle.write("CO1 TABLE COMBINATION S1+S2, fixed\n")
            handle.write("O2V TABLE COMBINATION S1+S2, fixed\n")
        handle.write("COUPLING FORM         c_cp * <MRSF|H|CV>\n")
        if result.ground_offset_hartree is not None:
            handle.write(
                f"GROUND OFFSET A_G     {result.ground_offset_hartree: .12f} Eh"
                f"  {result.ground_offset_hartree * HARTREE_TO_EV: .8f} eV\n"
            )
        if result.ground_offset_operator_hartree is not None:
            handle.write(
                "A_G OPERATOR CHECK    "
                f"{result.ground_offset_operator_hartree: .12f} Eh\n"
            )
        if result.ground_offset_source_error_hartree is not None:
            handle.write(
                "A_G CHECK ERROR       "
                f"{result.ground_offset_source_error_hartree: .6e} Eh\n"
            )
        if result.coupling_frobenius_norm is None:
            handle.write("COUPLING FROB. NORM   not assembled (matrix-free)\n")
        else:
            handle.write(
                f"COUPLING FROB. NORM   {result.coupling_frobenius_norm: .12e}\n"
            )
        if result.mrsf_result is not None:
            _write_solver_diagnostics(handle, result.mrsf_result, "MRSF")
        else:
            handle.write("\nMRSF EIGENSOLVER\n")
            _line(handle)
            handle.write("NOT RUN              direct enlarged-space EMRSF mode\n")
        _write_solver_diagnostics(handle, result, "EMRSF")
        if result.mrsf_result is not None:
            _write_mrsf_states(
                handle,
                result.mrsf_result,
                top_configurations=int(top_configurations),
            )
        _write_emrsf_states(
            handle, result, top_configurations=int(top_configurations)
        )
        _write_emrsf_decompositions(handle, result)
        if result.mrsf_result is not None:
            _write_state_correlations(handle, result, descriptors)
        _write_descriptors(handle, descriptors)
        _write_transition_properties(
            handle,
            transition_properties,
            target_multiplicity=result.target_multiplicity,
        )
        _write_coupling_audit(handle, coupling_audit)
        _write_lr_cv_diagonal_audit(handle, lr_cv_audit)
        _write_footer(handle)
    return output
