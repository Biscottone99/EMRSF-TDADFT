def _write_state_correlations(handle, result, descriptors) -> None:
    descriptor_by_state = _descriptor_map(descriptors)
    emrsf_symmetries = result.state_symmetries()
    mrsf_symmetries = result.mrsf_result.state_symmetries()
    emrsf_terms = term_labels(emrsf_symmetries)
    mrsf_terms = term_labels(mrsf_symmetries)
    handle.write("\nMRSF <-> EMRSF STATE CORRELATION\n")
    _line(handle)
    handle.write(
        "TERM matching is an ordinal-within-irrep diagnostic (for example, "
        "2 B1 with 2 B1); it is not an assumed paper-specific root map.\n"
    )
    handle.write(
        "Conditional overlap < 0.5 is flagged but does not redirect a term to a "
        "different state. CAND is the best-overlap diagnostic root; overlap "
        "columns refer to MR, or to CAND when MR is --.\n"
    )
    handle.write(
        " EM  MR CAND  EMTERM  MRTERM STATUS                         gamma_CV"
        "   |<MR|EM>|^2   conditional   dE(abs)/eV  dE(exc)/eV    mu/eA\n"
    )
    for match in result.state_matches():
        descriptor = (
            descriptor_by_state.get(match.mrsf_state)
            if match.matched
            else None
        )
        mu = descriptor.mu_e_angstrom if descriptor is not None else np.nan
        mr_text = f"{match.mrsf_state:3d}" if match.matched else " --"
        candidate_text = (
            f"{match.candidate_mrsf_state:4d}"
            if match.candidate_mrsf_state is not None
            else "  --"
        )
        mr_term = (
            mrsf_terms[match.mrsf_state]
            if match.matched
            else "--"
        )
        handle.write(
            f"{match.emrsf_state:3d} {mr_text} {candidate_text}"
            f" {emrsf_terms[match.emrsf_state]:>7s}"
            f" {mr_term:>7s}"
            f" {match.status:<30s}"
            f" {result.cv_weights[match.emrsf_state]:12.8f}"
            f" {match.overlap_squared:14.8f}"
            f" {match.conditional_overlap_squared:13.8f}"
            f" {match.raw_energy_shift_ev:12.7f}"
            f" {match.excitation_energy_shift_ev:12.7f}"
            f" {mu:10.6f}\n"
        )


def _write_emrsf_decompositions(handle, result) -> None:
    if not result.state_decompositions:
        return
    handle.write("\nEMRSF EIGENVALUE BLOCK DECOMPOSITION\n")
    _line(handle)
    handle.write(
        "For each normalized enlarged-space eigenvector, E is reconstructed as\n"
    )
    handle.write(
        "<X_M|A_MRSF|X_M> + <X_CV|A_CV+A_G|X_CV> "
        "+ 2<X_M|C|X_CV>.\n"
    )
    handle.write(
        " STATE      W_MRSF       W_CV       MRSF/Eh         CV/Eh"
        "      2C/Eh       closure/Eh\n"
    )
    for value in result.state_decompositions:
        handle.write(
            f" {value.state:5d}"
            f" {value.mrsf_weight:12.8f}"
            f" {value.cv_weight:12.8f}"
            f" {value.mrsf_block_hartree:14.8f}"
            f" {value.cv_block_hartree:14.8f}"
            f" {value.coupling_hartree:12.8f}"
            f" {value.closure_error_hartree:16.6e}\n"
        )


def _write_footer(handle) -> None:
    handle.write("\n")
    _line(handle, "=")
    handle.write("               **** PYSCF-EMRSF NORMAL TERMINATION ****\n")
    _line(handle, "=")


